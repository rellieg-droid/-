// Helper function to find a word in dictionary with fallback and clean-up
export function lookupWord(rawWord: string): WordEntry {
  const clean = rawWord
    .trim()
    .replace(/[.,/#!$%^&*;:{}=\-_`~()?"'«»¡!¿]/g, "")
    .toLowerCase();

  if (!clean) {
    return {
      word: rawWord,
      translation: rawWord,
      explanation: "מילה בספרדית",
      phonetic: rawWord,
      sentence: rawWord,
      sentenceHe: rawWord
    };
  }

  // Exact match
  if (DICTIONARY[clean]) {
    return DICTIONARY[clean];
  }

  // Check original capitalization match
  const origClean = rawWord.trim().replace(/[.,/#!$%^&*;:{}=\-_`~()?"'«»¡!¿]/g, "");
  if (DICTIONARY[origClean]) {
    return DICTIONARY[origClean];
  }

  // Common singularization fallback for plurals (-s, -es)
  if (clean.endsWith('es') && DICTIONARY[clean.slice(0, -2)]) {
    const base = DICTIONARY[clean.slice(0, -2)];
    return {
      word: origClean,
      translation: base.translation + " (רבים)",
      explanation: `צורת רבים של המילה ${base.word}: ${base.explanation}`,
      phonetic: base.phonetic + "-s",
      sentence: base.sentence,
      sentenceHe: base.sentenceHe
    };
  }

  if (clean.endsWith('s') && DICTIONARY[clean.slice(0, -1)]) {
    const base = DICTIONARY[clean.slice(0, -1)];
    return {
      word: origClean,
      translation: base.translation + " (רבים)",
      explanation: `צורת רבים של המילה ${base.word}: ${base.explanation}`,
      phonetic: base.phonetic + "-s",
      sentence: base.sentence,
      sentenceHe: base.sentenceHe
    };
  }

  // Default fallback if not directly indexed
  return {
    word: origClean || rawWord,
    translation: "מילה בספרדית",
    explanation: "לחץ על 'הוסף ללמידה' כדי לשמור מילה זו לתרגול וכרטיסיות.",
    phonetic: (origClean || rawWord).toLowerCase(),
    sentence: `La palabra "${origClean || rawWord}" en español.`,
    sentenceHe: `המילה "${origClean || rawWord}" בספרדית.`
  };
}

// Cache for dynamically translated words
const dynamicCache: Record<string, WordEntry> = {};

export async function fetchWordTranslation(rawWord: string, contextSentence?: string): Promise<WordEntry> {
  const local = lookupWord(rawWord);
  if (local.translation !== "מילה בספרדית" && !local.translation.includes("(רבים)")) {
    return local;
  }

  const clean = rawWord.trim().replace(/[.,/#!$%^&*;:{}=\-_`~()?"'«»¡!¿]/g, "").toLowerCase();
  if (dynamicCache[clean]) {
    return dynamicCache[clean];
  }

  try {
    const res = await fetch('/api/translate-word', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ word: rawWord, contextSentence }),
    });

    if (res.ok) {
      const data = await res.json();
      if (data && data.translation) {
        dynamicCache[clean] = data;
        return data;
      }
    }
  } catch (e) {
    console.warn('Dynamic translation failed, using local fallback:', e);
  }

  return local;
}
